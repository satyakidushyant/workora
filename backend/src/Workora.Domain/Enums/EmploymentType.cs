/// Represents the employment engagement type.
/// </summary>
public enum EmploymentType
{
    /// <summary>
    /// Regular permanent full-time employment.
    /// </summary>
    FullTime = 1,

    /// <summary>
    /// Part-time employment.
    /// </summary>
    PartTime = 2,

    /// <summary>
    /// Contractual / fixed-term engagement.
    /// </summary>
    Contract = 3,

    /// <summary>
    /// Internship engagement.
    /// </summary>
    Intern = 4
}
